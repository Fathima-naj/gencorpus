let n1=2;
let n2=3;
let operator="&";

switch(operator){
    case "+":
        console.log(n1+n2);
        break;
    case "-":
        console.log(n1-n2)
        break;  
    case "*":
        console.log(n1*n2)
        break; 
    case "/":
        console.log(n1/n2)
        break; 
    default :
        console.log("invalid operator");
        
}