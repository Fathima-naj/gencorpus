// Relational Operators


let a = 10; // Declare variable a
console.log("Relational Operators:");
console.log("a > 5:", a > 5);
console.log("a < 5:", a < 5);
console.log("a == 10:", a == 10);
console.log("a != 10:", a != 10);







// Increment/Decrement Operators

let b = 20; // Declare variable b
console.log("Increment/Decrement Operators:");
console.log("a before increment:", a);
console.log("a++ (post-increment):", a++); // Prints original value, then increments
console.log("a after increment:", a);
console.log("b before decrement:", b);
console.log("b-- (post-decrement):", b--); // Prints original value, then decrements
console.log("b after decrement:", b);



















// Shorthand Operators
let x = 10;
console.log("Shorthand Operators:");
x += 5;
console.log("x += 5:", x);
x -= 3;
console.log("x -= 3:", x);
x *= 2;
console.log("x *= 2:", x);








// Logical Operators
console.log("Logical Operators:");
console.log("a > 5 && b > 19:", a > 5 && b > 19); // Adjusted b to match the decrement
console.log("a > 5 || b > 19:", a > 5 || b > 19);
console.log("!(a > 5):", !(a > 5));







// Decision-Making Statements
console.log("Decision-Making Statements:");
if (a > 5) {
  console.log("a is greater than 5");
} else {
  console.log("a is less than or equal to 5");
}
